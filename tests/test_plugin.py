"""Claude Code plugin package (plugin/ + .claude-plugin/marketplace.json): repo files only."""
import importlib.util
import json
import os
import re
import shutil
import subprocess
import tempfile
import unittest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PLUGIN = os.path.join(ROOT, "plugin")
FA = os.path.join("plugins", "orbit")
EVENTS = {"PreToolUse", "PostToolUse", "PostToolUseFailure", "PermissionRequest", "UserPromptSubmit", "Notification",
          "Stop", "SubagentStart", "SubagentStop", "SessionStart", "SessionEnd", "PreCompact", "PostCompact"}
KEBAB = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
VAR = re.compile(r"\$\{CLAUDE_PLUGIN_ROOT\}/([^\"\\\s]+)")
# Generated by the build (not copies): must not carry personal paths or private tool names.
GENERATED = ("plugin/.claude-plugin/plugin.json", "plugin/hooks/hooks.json", "plugin/.mcp.json",
             ".claude-plugin/marketplace.json", "hooks/pl_mark.py", "scripts/build_plugin.py")
# ⚠Private project/company words come from tests/.private-deny (gitignored), never hard-coded here; «saver» stays
# literal because it is also a public Sidereus feature name and so cannot go into the shared deny file.
_PRIV = os.path.join(ROOT, "tests", ".private-deny")
_WORDS = [w.strip() for w in (open(_PRIV, encoding="utf-8").read().splitlines() if os.path.exists(_PRIV) else [])
          if w.strip() and not w.startswith("#")]
DENY = re.compile("|".join([r"/Users/|/home/|~/\.claude|saver|agent-brief"] + [re.escape(w) for w in _WORDS]), re.I)  # leakscan: allow


def _load_build():
    spec = importlib.util.spec_from_file_location("build_plugin", os.path.join(ROOT, "scripts", "build_plugin.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _json(rel):
    with open(os.path.join(ROOT, rel), encoding="utf-8") as f:
        return json.load(f)


class PluginTest(unittest.TestCase):
    def test_manifest(self):
        m = _json("plugin/.claude-plugin/plugin.json")
        self.assertRegex(m["name"], KEBAB)
        self.assertEqual(m["name"], "sidereus")   # public plugin id; MCP server stays "sidereus" (test_mcp)
        self.assertEqual(m["author"], {"name": "bugsterran"})
        for k in ("version", "description", "license"):
            self.assertTrue(m.get(k), k)

    def test_hook_events_and_paths(self):
        h = _json("plugin/hooks/hooks.json")
        self.assertEqual(set(h), {"hooks"})
        self.assertTrue(set(h["hooks"]) <= EVENTS, set(h["hooks"]) - EVENTS)
        for groups in h["hooks"].values():
            for g in groups:
                for c in g["hooks"]:
                    self.assertEqual(c["type"], "command")
                    self.assertIsInstance(c["timeout"], int)
                    self.assertIn('"${CLAUDE_PLUGIN_ROOT}/', c["command"])   # quoted: cache path may hold spaces
                    # every hook goes through the launcher (Windows: python3 may be the Store stub)
                    self.assertTrue(c["command"].startswith('sh "${CLAUDE_PLUGIN_ROOT}/hooks/pyrun.sh" "'), c["command"])

    def test_plugin_root_paths_exist(self):
        for rel in ("plugin/hooks/hooks.json", "plugin/.mcp.json"):
            with open(os.path.join(ROOT, rel), encoding="utf-8") as f:
                paths = VAR.findall(f.read())
            self.assertTrue(paths, rel)
            for p in paths:
                self.assertNotIn("..", p.split("/"))
                self.assertTrue(os.path.isfile(os.path.join(PLUGIN, p)), p)

    def test_mcp(self):
        s = _json("plugin/.mcp.json")["mcpServers"]["sidereus"]
        self.assertEqual(s["command"], "${SIDEREUS_PYTHON:-python3}")   # Windows: python3 is the Store alias
        self.assertEqual(s["args"], ["${CLAUDE_PLUGIN_ROOT}/mcp/sidereus_mcp.py"])

    def test_marketplace_points_at_plugin(self):
        mk = _json(".claude-plugin/marketplace.json")
        self.assertRegex(mk["name"], KEBAB)
        self.assertEqual((mk["name"], [p["name"] for p in mk["plugins"]]), ("sidereus", ["sidereus", "orbit"]))
        self.assertEqual(mk["owner"], {"name": "bugsterran"})
        self.assertEqual([p["source"] for p in mk["plugins"]], ["./plugin", "./plugins/orbit"])
        for p in mk["plugins"]:
            self.assertEqual(_json(os.path.join(p["source"], ".claude-plugin", "plugin.json"))["name"], p["name"])

    def test_orbit_plugin(self):
        # Hand-written plugin: manifest, quoted plugin-root hook path that exists, executable bin, skill front matter.
        m = _json(os.path.join(FA, ".claude-plugin", "plugin.json"))
        self.assertEqual((m["name"], m["author"], m["license"]), ("orbit", {"name": "bugsterran"}, "MIT"))
        h = _json(os.path.join(FA, "hooks", "hooks.json"))
        self.assertEqual(set(h["hooks"]), {"SessionStart"})
        (g,) = h["hooks"]["SessionStart"]
        self.assertEqual(g["matcher"], "startup|resume")
        (c,) = g["hooks"]
        self.assertEqual((c["type"], c["timeout"]), ("command", 3))
        self.assertIn('"${CLAUDE_PLUGIN_ROOT}/', c["command"])
        for p in VAR.findall(c["command"]):
            self.assertNotIn("..", p.split("/"))
            self.assertTrue(os.path.isfile(os.path.join(ROOT, FA, p)), p)
        for b in ("orbit", "claude-account"):     # claude-account = pre-rename alias
            self.assertTrue(os.access(os.path.join(ROOT, FA, "bin", b), os.X_OK), b)
        with open(os.path.join(ROOT, FA, "skills", "account", "SKILL.md"), encoding="utf-8") as f:
            head = f.read().split("---")[1]
        for k in ("name: account", "disable-model-invocation: true", "allowed-tools: Bash(orbit list), Bash(orbit)"):
            self.assertIn(k, head)

    def test_up_to_date_and_allow_listed(self):
        # Byte-equal copies + generated manifests + nothing outside the allow-list (run scripts/build_plugin.py).
        self.assertEqual(_load_build().stale(), [])

    def test_ev_hook_shipped(self):
        # Evidence hook: allow-listed, byte-equal copy, registered for the three Bash events.
        self.assertIn("hooks/ev_hook.py", _load_build().COPY)
        with open(os.path.join(ROOT, "hooks", "ev_hook.py"), "rb") as a, \
                open(os.path.join(PLUGIN, "hooks", "ev_hook.py"), "rb") as b:
            self.assertEqual(a.read(), b.read())
        h = _json("plugin/hooks/hooks.json")["hooks"]
        for e in ("PreToolUse", "PostToolUse", "PostToolUseFailure"):
            cmds = [c for g in h[e] if g.get("matcher") == "Bash" for c in g["hooks"] if "ev_hook.py" in c["command"]]
            self.assertEqual([c["timeout"] for c in cmds], [3], e)

    def test_perm_mark_matcher(self):
        # MCP elicitation dialogs mark «Awaiting approval» like permission prompts.
        h = _json("plugin/hooks/hooks.json")["hooks"]
        ms = [g.get("matcher") for g in h["Notification"] if any("perm_mark.py" in c["command"] for c in g["hooks"])]
        self.assertEqual(ms, ["permission_prompt|elicitation_dialog"])

    def test_no_skills_dir(self):
        self.assertFalse(os.path.exists(os.path.join(PLUGIN, "skills")))

    def test_generated_files_clean(self):
        for rel in GENERATED:
            with open(os.path.join(ROOT, rel), encoding="utf-8") as f:
                for n, line in enumerate(f, 1):
                    if "leakscan: allow" in line:
                        continue
                    self.assertIsNone(DENY.search(line), "%s:%d" % (rel, n))


class SelfContainedTest(unittest.TestCase):
    """A copy of plugin/ (what `/plugin install` caches, no clone) imports nothing but stdlib and its own files."""
    PLATFORM_ONLY = {"fcntl", "msvcrt", "winreg", "_winapi", "termios", "pwd", "grp", "resource"}

    def setUp(self):
        import sysconfig
        self.tmp = tempfile.mkdtemp()
        self.copy = os.path.realpath(os.path.join(self.tmp, "plugin"))
        shutil.copytree(PLUGIN, self.copy)
        self.std = tuple(os.path.realpath(p) + os.sep for p in {sysconfig.get_paths()["stdlib"],
                                                               sysconfig.get_paths()["platstdlib"]})

    def tearDown(self):
        shutil.rmtree(self.tmp, ignore_errors=True)

    def sources(self):
        for d in ("", "hooks", "mcp"):
            base = os.path.join(self.copy, d)
            for n in sorted(os.listdir(base)):
                if n.endswith(".py"):
                    yield os.path.join(base, n)

    def is_std(self, f):
        return os.path.realpath(f).startswith(self.std)

    def test_imports_resolve_inside_copy(self):
        import ast
        import importlib.util as iu
        own = {os.path.basename(p)[:-3] for p in self.sources()}
        for path in self.sources():
            with open(path, encoding="utf-8") as f:
                tree = ast.parse(f.read(), path)
            for node in ast.walk(tree):
                if isinstance(node, ast.Import):
                    names = [a.name.split(".")[0] for a in node.names]
                elif isinstance(node, ast.ImportFrom):
                    self.assertEqual(node.level, 0, path)
                    names = [node.module.split(".")[0]]
                else:
                    continue
                for n in names:
                    if n in own or n in self.PLATFORM_ONLY:
                        continue
                    spec = iu.find_spec(n)
                    self.assertIsNotNone(spec, "%s: %s" % (os.path.basename(path), n))
                    ok = spec.origin in ("built-in", "frozen") or self.is_std(spec.origin or "")
                    self.assertTrue(ok, "%s imports non-stdlib %s (%s)" % (os.path.basename(path), n, spec.origin))

    def test_load_from_copy_only(self):
        import contextlib
        import io
        import sys
        from unittest import mock
        own = {os.path.basename(p)[:-3] for p in self.sources()}
        saved_mods, saved_path = dict(sys.modules), list(sys.path)
        for n in own:      # ⚠a repo copy already imported (mailbox_config) would satisfy the import from outside the copy
            sys.modules.pop(n, None)
        sys.path[:] = [p for p in sys.path if (os.path.realpath(p or os.getcwd()) + os.sep).startswith(self.std)]
        env = {"MAILBOX_DIR": os.path.join(self.tmp, "data"), "CLAUDE_CONFIG_DIR": os.path.join(self.tmp, "cc"),
               "HOME": self.tmp, "USERPROFILE": self.tmp}
        try:
            with mock.patch.dict(os.environ, env), contextlib.redirect_stderr(io.StringIO()):   # config-missing notice
                for k in ("MAILBOX_CONFIG", "SIDEREUS_PORT"):
                    os.environ.pop(k, None)
                files = [p for p in self.sources() if os.path.dirname(p) != self.copy]
                for i, path in enumerate(files):
                    spec = importlib.util.spec_from_file_location("plugin_copy_%d" % i, path)
                    mod = importlib.util.module_from_spec(spec)
                    spec.loader.exec_module(mod)
            outside = sorted(n for n, m in sys.modules.items() if n not in saved_mods
                             and getattr(m, "__file__", None) and not self.is_std(m.__file__)
                             and not os.path.realpath(m.__file__).startswith(self.copy + os.sep))
            self.assertEqual(outside, [])
            self.assertTrue(len(files) >= 10, files)
        finally:
            sys.path[:] = saved_path
            for n in [n for n in sys.modules if n not in saved_mods]:
                del sys.modules[n]
            sys.modules.update(saved_mods)


@unittest.skipIf(os.name == "nt" or not os.path.exists("/bin/sh"), "POSIX sh stubs")
class PyrunTest(unittest.TestCase):
    """hooks/pyrun.sh with a fake PATH of stub interpreters (POSIX sh only; no real Python is run)."""
    def setUp(self):
        self.tmp = tempfile.mkdtemp()

    def tearDown(self):
        shutil.rmtree(self.tmp)

    def stub(self, name, ok, d=None):
        # ok: passes the version probe and prints its own path (sys.executable); the real run echoes name, args, stdin.
        # A probe also appends to probes.log, so a test can tell a cached run (no probe) from a probed one.
        p = os.path.join(d or self.tmp, name)
        log = os.path.join(self.tmp, "probes.log")
        with open(p, "w", encoding="utf-8") as f:
            f.write('#!/bin/sh\ncase " $* " in *" -c "*) echo %s >>"%s"; [ %d = 0 ] && printf %%s "$0"; exit %d;; esac\n'
                    'echo "%s $*"; cat; exit 7\n' % (name, log, 0 if ok else 9, 0 if ok else 9, name))
        os.chmod(p, 0o755)

    def probes(self):
        log = os.path.join(self.tmp, "probes.log")
        if not os.path.exists(log):
            return []
        with open(log, encoding="utf-8") as f:
            names = f.read().split()
        os.remove(log)
        return names

    def run_sh(self, os_name, path=None, **extra):
        # ⚠PATH = stubs only (+ cat/mv/rm): a real python/py in /usr/bin would win the probe on some hosts.
        for tool in ("cat", "mv", "rm"):
            if not os.path.exists(os.path.join(self.tmp, tool)):
                os.symlink(shutil.which(tool), os.path.join(self.tmp, tool))
        env = dict({"PATH": path or self.tmp, "CLAUDE_PLUGIN_DATA": self.tmp}, **extra)
        if os_name:
            env["OS"] = os_name
        return subprocess.run(["/bin/sh", os.path.join(ROOT, "hooks", "pyrun.sh"), "a b.py", "x"], input="{}",
                              env=env, capture_output=True, text=True, timeout=10, encoding="utf-8")

    def drop_cache(self):
        c = os.path.join(self.tmp, "sidereus-pyrun.cache")
        if os.path.exists(c):
            os.remove(c)

    def test_non_windows_runs_python3_unprobed(self):
        self.stub("python3", False)    # probe would fail; must not be probed off Windows
        r = self.run_sh(None)
        self.assertEqual((r.returncode, r.stdout), (7, "python3 a b.py x\n{}"))
        self.stub("mypy3", False)
        r = self.run_sh(None, SIDEREUS_PYTHON="mypy3")
        self.assertEqual((r.returncode, r.stdout), (7, "mypy3 a b.py x\n{}"))

    def test_windows_order(self):
        self.stub("python3", False)
        self.stub("py", True)
        self.stub("python", True)
        r = self.run_sh("Windows_NT")
        self.assertEqual((r.returncode, r.stdout, self.probes()), (7, "py a b.py x\n{}", ["py"]))
        self.drop_cache()
        os.remove(os.path.join(self.tmp, "py"))
        r = self.run_sh("Windows_NT")
        self.assertEqual((r.returncode, r.stdout, self.probes()), (7, "python a b.py x\n{}", ["python3", "python"]))
        self.drop_cache()
        self.stub("python3", True)
        r = self.run_sh("Windows_NT")
        self.assertEqual((r.returncode, r.stdout), (7, "python3 a b.py x\n{}"))

    def test_windows_cache_hit_runs_no_probe(self):
        self.stub("py", True)
        self.assertEqual(self.run_sh("Windows_NT").stdout, "py a b.py x\n{}")
        self.assertEqual(self.probes(), ["py"])
        r = self.run_sh("Windows_NT")
        self.assertEqual((r.returncode, r.stdout, self.probes()), (7, "py a b.py x\n{}", []))
        os.remove(os.path.join(self.tmp, "py"))     # cached exe gone -> probe again
        self.stub("python", True)
        r = self.run_sh("Windows_NT")
        self.assertEqual((r.stdout, self.probes()), ("python a b.py x\n{}", ["python"]))

    def test_windows_skips_store_alias_unrun(self):
        apps = os.path.join(self.tmp, "WindowsApps")
        os.mkdir(apps)
        self.stub("python3", True, apps)     # a working-looking alias must still never be run
        self.stub("python", True)
        r = self.run_sh("Windows_NT", path=apps + os.pathsep + self.tmp)
        self.assertEqual((r.stdout, self.probes()), ("python a b.py x\n{}", ["python"]))

    def test_windows_override(self):
        self.stub("py", True)
        self.stub("mypy", False)
        r = self.run_sh("Windows_NT", SIDEREUS_PYTHON=os.path.join(self.tmp, "mypy"))
        self.assertEqual((r.returncode, r.stdout, self.probes()), (7, "mypy a b.py x\n{}", []))

    def test_windows_none_found(self):
        self.stub("python3", False)
        r = self.run_sh("Windows_NT")
        self.assertEqual((r.returncode, r.stdout), (127, ""))
        self.assertIn("no Python 3.9+", r.stderr)


